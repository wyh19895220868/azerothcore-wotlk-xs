-- =============================================================================
-- 背景：
--   `_模板_物品鉴定` 全部 5405 行都在引用 `物品属性_模板_组 = 101`（追加属性）、
--   `物品强化_系统 = 1`（追加强化），但 `_模板_物品属性` 里没有 组=101 的任何记录，
--   `_模板_物品强化` 里也只有 组=0 的记录。鉴定流程在
--       ApplyAdditionalAttributes -> GenerateRandomAttributes 取不到候选属性时返回 nullopt，
--       ApplyItemEnhancement 取不到强化组时返回 0，
--   再由 `incomplete` 判定直接取消整次鉴定，所以客户端永远拿不到
--   “追加属性 / 追加套装 / 追加强化” 三段 Tooltip 数据。
--
--   另外 `_模板_物品鉴定.物品成长_系统` 一律写着 '0'，ParseCommaSeparatedNumbers("0") 得到 {0}，
--   ApplyItemGrowth 随机到 0 组必然返回 0，同样触发 incomplete 取消。
--   本文件对“成长属性最大数量 = 0”的行清空 `物品成长_系统`，让鉴定先能完整跑通；
--   后续要启用成长，请给这些行填入真实存在的 `_模板_物品成长`.`组`。
--
--   套装同理：`技能模板_套装_组` 全为 0，物品永远分配不到套装。
--   这里统一接入 组 3/4/5（`_模板_物品套装` 中 需求系统ID = 0 的三套，无需材料）。
--
-- 影响范围：只改 world 模板表，不动角色库数据。
-- 回滚：见文件末尾的 BACKUP 段。
-- =============================================================================

