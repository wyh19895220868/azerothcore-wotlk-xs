-- 动作触发功能表新增采集和移动触发类型。
-- 采矿、采药、钓鱼的内容可留空匹配所有来源，或填写游戏物体ID（多个ID用 # 分隔）。
-- 生物移动的内容必须填写生物模板ID（多个ID用 # 分隔）；触发对象为该生物的主人，或50码内最近的玩家。
ALTER TABLE `_动作触发功能表`
  MODIFY COLUMN `动作` enum(
    '说话','收到密语','击杀生物','击杀玩家','完成任务','完成成就','被玩家击杀','被生物击杀',
    '拾取指定物品','等级变化','切换地图','切换区域','离开地图','切换地区','离开区域','释放技能',
    '登陆','登出','第一次登陆','VIP等级变化','复活','装备物品','金币变化','获得经验','获得声望',
    '学习技能','遗忘技能','决斗开始','决斗中止','决斗胜利','决斗失败','释放尸体','学习天赋',
    '进入战斗','结束战斗','重置天赋','获得光环','失去光环','模型改变','表情',
    '采矿','采药','钓鱼','玩家移动','生物移动','接受任务','放弃任务','玩家死亡','任务奖励物品'
  ) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL DEFAULT '说话';

-- 旧模板将 /睡觉 误当作聊天文本。标准 /sleep 实际发送 TextEmote 87。
UPDATE `_动作触发功能表`
SET `内容` = '87'
WHERE `动作` = '表情' AND `内容` IN ('/睡觉', '/sleep');
