
DROP TABLE IF EXISTS `_模板_物品技能`;
CREATE TABLE `_模板_物品技能` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '技能模板唯一ID，主键',
  `注释` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NULL DEFAULT NULL COMMENT '技能的中文描述，用于管理员查看',
  `客户端显示` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NULL DEFAULT NULL COMMENT '客户端显示的技能描述，会在物品提示中显示',
  `组` int UNSIGNED NOT NULL DEFAULT 0 COMMENT '技能组ID，相同组的技能属于同一系列（如火系、冰系），可用于升级或随机选择',
  `等级` int UNSIGNED NOT NULL DEFAULT 1 COMMENT '技能在组内的等级，1级为基础，数字越大等级越高',
  `技能id` int NOT NULL DEFAULT 0 COMMENT '游戏中实际的技能ID，对应spell.dbc中的ID',
  `几率` float NOT NULL DEFAULT 100 COMMENT '选择权重：同组内有多个技能时，此值越高被选中概率越大。计算方式：该技能几率/同组所有技能几率之和',
  `技能触发类型` tinyint UNSIGNED NOT NULL DEFAULT 0 COMMENT '技能触发类型：0=使用触发，1=装备触发，2=击中触发，100=学习技能',
  `触发几率` float NOT NULL DEFAULT 100 COMMENT '技能触发几率：0-100之间的数值，表示技能触发的百分比概率。例如：50表示50%几率触发',
  `技能使用次数` smallint NOT NULL DEFAULT 0 COMMENT '技能使用次数：0=无限使用，负数=用完删除物品，正数=用完不删除物品',
  `技能每分钟触发次数` float NOT NULL DEFAULT 0 COMMENT '技能每分钟触发次数（PPM），仅当触发类型为2(击中触发)时有效',
  `技能冷却时间` tinyint NOT NULL DEFAULT 0 COMMENT '技能冷却时间模式：0=官方冷却，1=无冷却，2=自定义冷却值',
  `技能冷却值` int NOT NULL DEFAULT 0 COMMENT '技能冷却值，单位毫秒（1000=1秒），仅当技能冷却时间=2时生效',
  `技能消耗` tinyint NOT NULL DEFAULT 0 COMMENT '技能消耗模式：0=官方消耗（法力/能量等），1=无消耗',
  `技能施法` tinyint NOT NULL DEFAULT 0 COMMENT '技能施法时间模式：0=官方施法时间+官方动画，1=无施法时间（瞬发）+有动画，2=无施法时间+无动画（静默模式）',
  `技能强化` tinyint NOT NULL DEFAULT 0 COMMENT '技能伤害/治疗强化模式：0=官方，1=固定值增幅，2=百分比增幅',
  `技能伤害` int NOT NULL DEFAULT 0 COMMENT '技能伤害/治疗增幅值：当强化=1时为固定附加值，当强化=2时为百分比（10=110%）',
  `技能类型` tinyint NOT NULL DEFAULT 0 COMMENT '技能类型：0=不修改，1=buff（修改持续时间）',
  `技能持续时间` int NOT NULL DEFAULT 0 COMMENT '技能持续时间，单位分钟，仅当技能类型=1时生效（1=1分钟，100=100分钟）',
  `启用状态` tinyint NOT NULL DEFAULT 1 COMMENT '是否启用：1=启用，0=禁用（禁用的技能不会被分配）',
  `优先级` int NOT NULL DEFAULT 0 COMMENT '技能优先级，数值越大优先级越高，用于解决技能冲突',
  PRIMARY KEY (`id`) USING BTREE,
  KEY `idx_group_level` (`组`, `等级`) COMMENT '组和等级组合索引，优化按组查询',
  KEY `idx_triggertype` (`技能触发类型`) COMMENT '触发类型索引，优化按类型查询',
  KEY `idx_status` (`启用状态`) COMMENT '启用状态索引，快速过滤禁用技能'
) ENGINE = InnoDB AUTO_INCREMENT = 1 CHARACTER SET = utf8mb4 COLLATE = utf8mb4_general_ci COMMENT = '物品技能系统 - 技能模板库（通用技能模板，可添加到任意物品）' ROW_FORMAT = DYNAMIC;


